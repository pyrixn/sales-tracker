#!/usr/bin/env node
/**
 * Build script for the Supabase Edge Function: concatenates core modules + Postgres adapter + router
 * into a single Deno-compatible index.ts with `import postgres from 'npm:postgres'` at the top.
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '../src');
const DIST = path.join(__dirname, '../supabase/functions/api');

// Core modules in dependency order (minus migrate/exporter which aren't needed yet)
const ORDER = ['util', 'rates', 'ids', 'refs', 'ledger', 'sales', 'matching', 'views', 'reminders', 'undo', 'exporter'];

// Normalise line endings so the bundle is identical on LF and CRLF checkouts.
function read(p) { return fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n'); }
function write(p, s) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s, 'utf8'); }

function main() {
  console.log('Building Edge Function...');
  const parts = [];

  // 1. Header (import postgres and supabase, build db wrapper)
  parts.push(`// ── Generated by tools/build-edge.js ──────────────────────────────────────────
import postgres from 'npm:postgres';
import { createClient } from 'npm:@supabase/supabase-js@2';

// Build db wrapper { query, transaction }
const DB_URL = Deno.env.get('SUPABASE_DB_URL');
let db;

if (DB_URL) {
  const sql = postgres(DB_URL, { prepare: false });
  db = {
    query: async (text, params) => {
      const rows = await sql.unsafe(text, params || []);
      return { rows };
    },
    transaction: async (fn) => {
      return sql.begin(async (tsql) => {
        const tx = {
          query: async (text, params) => {
            const rows = await tsql.unsafe(text, params || []);
            return { rows };
          },
          // A nested transaction joins this one, so applyOps inside a locked write stays atomic with it.
          transaction: async (inner) => inner(tx)
        };
        return fn(tx);
      });
    }
  };
} else {
  const SUPABASE_URL = Deno.env.get('SUPABASE_URL') || '';
  const SUPABASE_SERVICE_ROLE_KEY = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') || Deno.env.get('SUPABASE_ANON_KEY') || '';
  if (!SUPABASE_URL || !SUPABASE_SERVICE_ROLE_KEY) {
    throw new Error('Neither SUPABASE_DB_URL nor SUPABASE_SERVICE_ROLE_KEY is set');
  }
  const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY);
  db = {
    query: async (text, params) => {
      params = params || [];
      const clean = text.replace(/\\s+/g, ' ').trim();

      // 0. Write lock: this fallback has no real transactions, so there is nothing to lock.
      if (/^SELECT pg_advisory_xact_lock\\(/i.test(clean)) return { rows: [] };

      // 0b. SELECT * FROM table WHERE upper(col) = $1 (case-insensitive match; params[0] is already upper-case)
      let m = clean.match(/^SELECT \\* FROM ([a-z_]+) WHERE upper\\(([a-z_]+)\\) = \\$1/i);
      if (m) {
        const r = await supabase.from(m[1]).select('*').ilike(m[2], String(params[0]).replace(/[\\\\%_]/g, '\\\\$&'));
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: r.data || [] };
      }

      // 1. SELECT * FROM table WHERE col = $1
      m = clean.match(/^SELECT \\* FROM ([a-z_]+) WHERE ([a-z_]+) = \\$1/i);
      if (m) {
        const r = await supabase.from(m[1]).select('*').eq(m[2], params[0]);
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: r.data || [] };
      }

      // 2. SELECT * FROM table (optional ORDER BY)
      m = clean.match(/^SELECT \\* FROM ([a-z_]+)(?: ORDER BY ([a-z_]+))?/i);
      if (m) {
        let q = supabase.from(m[1]).select('*');
        if (m[2]) q = q.order(m[2]);
        const r = await q;
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: r.data || [] };
      }

      // 3. SELECT key, value FROM settings
      if (/^SELECT key, value FROM settings/i.test(clean)) {
        const r = await supabase.from('settings').select('key, value');
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: r.data || [] };
      }

      // 4. SELECT response FROM request_log WHERE request_id = $1
      m = clean.match(/^SELECT response FROM request_log WHERE request_id = \\$1/i);
      if (m) {
        const r = await supabase.from('request_log').select('response').eq('request_id', params[0]);
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: r.data || [] };
      }

      // 5. SELECT 1 FROM payment_inbox WHERE transaction_id = $1 LIMIT 1
      m = clean.match(/^SELECT 1 FROM payment_inbox WHERE transaction_id = \\$1 LIMIT 1/i);
      if (m) {
        const r = await supabase.from('payment_inbox').select('id').eq('transaction_id', params[0]).limit(1);
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: (r.data && r.data.length) ? [{ exists: 1 }] : [] };
      }

      // 6. SELECT 1 FROM payment_inbox WHERE raw_sms = $1 AND transaction_id = '' LIMIT 1
      m = clean.match(/^SELECT 1 FROM payment_inbox WHERE raw_sms = \\$1 AND transaction_id = '' LIMIT 1/i);
      if (m) {
        const r = await supabase.from('payment_inbox').select('id').eq('raw_sms', params[0]).eq('transaction_id', '').limit(1);
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: (r.data && r.data.length) ? [{ exists: 1 }] : [] };
      }

      // 7. INSERT INTO settings ... ON CONFLICT
      if (/^INSERT INTO settings/i.test(clean)) {
        const r = await supabase.from('settings').upsert({ key: params[0], value: String(params[1]) }, { onConflict: 'key' });
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: [] };
      }

      // 8. INSERT INTO request_log ... ON CONFLICT
      if (/^INSERT INTO request_log/i.test(clean)) {
        const r = await supabase.from('request_log').upsert({ request_id: params[0], response: params[1] }, { onConflict: 'request_id', ignoreDuplicates: true });
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: [] };
      }

      // 9. INSERT INTO table (cols...) VALUES ($1, $2...)
      m = clean.match(/^INSERT INTO ([a-z_]+) \\(([^)]+)\\) VALUES/i);
      if (m) {
        const table = m[1];
        const cols = m[2].split(',').map(s => s.trim());
        const row = {};
        cols.forEach((c, idx) => { row[c] = params[idx]; });
        const r = await supabase.from(table).insert(row);
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: [] };
      }

      // 10. UPDATE table SET ... WHERE col = $N
      m = clean.match(/^UPDATE ([a-z_]+) SET (.+) WHERE ([a-z_]+) = \\$(\\d+)/i);
      if (m) {
        const table = m[1];
        const sets = m[2].split(',').map(s => s.trim());
        const whereCol = m[3];
        const whereIdx = Number(m[4]) - 1;
        const updates = {};
        sets.forEach(s => {
          const parts = s.split('=').map(p => p.trim());
          const col = parts[0];
          const paramIdx = Number(parts[1].replace('$', '')) - 1;
          updates[col] = params[paramIdx];
        });
        const r = await supabase.from(table).update(updates).eq(whereCol, params[whereIdx]);
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: [] };
      }

      // 11. DELETE FROM table WHERE col = $1
      m = clean.match(/^DELETE FROM ([a-z_]+) WHERE ([a-z_]+) = \\$1/i);
      if (m) {
        const r = await supabase.from(m[1]).delete().eq(m[2], params[0]);
        if (r.error) throw new Error(r.error.message || r.error);
        return { rows: [] };
      }

      throw new Error('Unsupported SQL: ' + clean);
    },
    transaction: async (fn) => fn(db)
  };
}
`);

  // 2. Core modules
  parts.push('// ── Core modules ─────────────────────────────────────────────────────────────\n');
  parts.push('var Core = {};\n');
  ORDER.forEach(name => {
    const p = path.join(SRC, 'core', name + '.js');
    if (!fs.existsSync(p)) { console.warn('Missing:', p); return; }
    const src = read(p);
    // Strip trailing `if (typeof module...)` line
    const clean = src.replace(/if\s*\(\s*typeof\s+module\s*!==\s*['"]undefined['"]\s*\).*$/m, '').trim();
    parts.push(`\n// ── core/${name}.js ──\n${clean}\n`);
  });

  // 2b. UI (served by the function at GET /)
  const uiPath = path.join(SRC, 'ui', 'Index.html');
  if (!fs.existsSync(uiPath)) throw new Error('Missing src/ui/Index.html');
  parts.push(`\n// ── Admin UI (served at GET /) ──\nvar UI_HTML = ${JSON.stringify(read(uiPath))};\n`);

  // 3. Postgres adapter
  const adapterPath = path.join(SRC, 'adapters/postgres.js');
  if (!fs.existsSync(adapterPath)) throw new Error('Missing postgres.js adapter');
  const adapterSrc = read(adapterPath).replace(/if\s*\(\s*typeof\s+module\s*!==\s*['"]undefined['"]\s*\).*$/m, '').trim();
  parts.push(`\n// ── Postgres Adapter ─────────────────────────────────────────────────────────\n${adapterSrc}\n`);

  // 4. Edge router
  const routerPath = path.join(SRC, 'server/edge.js');
  if (!fs.existsSync(routerPath)) throw new Error('Missing edge.js router');
  const routerSrc = read(routerPath);
  parts.push(`\n${routerSrc}\n`);

  // 5. Footer (Deno.serve)
  parts.push(`\n// ── Deno entry ───────────────────────────────────────────────────────────────\nDeno.serve(handle);\n`);

  const bundle = parts.join('');
  const out = path.join(DIST, 'index.ts');
  write(out, bundle);
  console.log('✓ Built', out, `(${(bundle.length / 1024).toFixed(1)} KB)`);
}

main();
